"""
대안 생성 프롬프트
"""

def get_alternative_generation_prompt(stage: str, error: str, template_content: str) -> str:
    """오류별 대안 생성 프롬프트 생성"""
    return f"""다음 알림톡 템플릿 검증 오류에 대한 구체적이고 실용적인 대안 3개를 생성해주세요.

**검증 단계**: {stage}
**오류 내용**: {error}
**템플릿 내용**: {template_content[:500]}...

**요구사항**:
1. 각 대안은 구체적이고 실행 가능해야 함
2. 오류의 근본 원인을 해결하는 방향으로 제시
3. 알림톡 승인 기준을 준수하는 방향으로 제시
4. 사용자가 바로 적용할 수 있는 수준의 구체성

**응답 형식**:
대안1: [구체적인 수정 방안]
대안2: [구체적인 수정 방안]  
대안3: [구체적인 수정 방안]

각 대안은 50자 이내로 간결하게 작성해주세요."""
