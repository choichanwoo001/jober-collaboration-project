"""
대안 생성 프롬프트 (배치 처리용)
"""

def get_batch_alternative_generation_prompt(stage: str, errors: list, template_content: str) -> str:
    """여러 오류에 대한 대안을 한 번에 생성하는 프롬프트"""
    
    # 검증 규칙 정의
    validation_rules = """
    ## 알림톡 검증 규칙 (반드시 준수)

    ### 1. 정보성 메시지 요건
    - 반드시 정보성 메시지여야 함
    - 광고성 메시지는 불가
    - 앱 설치 유도 문구 포함 불가
    - 무료체험, 할인쿠폰, 포인트 적립, 경품 등 혜택 제공 안내 불가
    - 개인정보 등록/특정 행위(회원가입, 클릭 등) 유도 불가
    - 동의하지 않은 쿠폰 발급 안내 불가

    ### 2. 변수 사용 규칙
    - 변수는 최대 40개까지만 사용 가능
    - 템플릿이 변수로만 이루어질 수 없음
    - 버튼명, 미리보기 메시지에는 변수를 포함할 수 없음

    ### 3. 기타 템플릿 작성 규칙
    - 템플릿 내용과 무관한 문구, 불필요한 광고 안내 문구 포함 불가
    - 간단한 인사말(예: "안녕하세요") 정도는 허용
    - 알림톡은 연령인증 메시지 기능을 제공하지 않으므로, 연령인증 기능을 적용한 후 예외 발송이 허용되는 업종 및 콘텐츠는 발송할 수 없음
    """
    
    # 오류 목록을 문자열로 변환
    errors_text = "\n".join([f"- {i+1}. {error}" for i, error in enumerate(errors)])
    
    return f"""다음 알림톡 템플릿의 **모든 검증 오류에 대해 각각 3개씩의 대안**을 생성해주세요.
    총 {len(errors)}개 오류에 대해 {len(errors) * 3}개의 대안이 필요합니다.

{validation_rules}

**검증 단계**: {stage}
**발견된 오류들**:
{errors_text}

**템플릿 내용**: {template_content[:500]}...

**중요 요구사항**:
1. **각 오류별로 3개씩 대안을 생성해야 함**
2. **모든 대안은 위 검증 규칙을 준수해야 함**
3. **각 오류의 근본 원인을 해결하는 방향으로 제시**
4. **사용자가 바로 적용할 수 있는 구체적인 수정 방안**
5. **원본 템플릿의 의도는 유지하면서 규칙만 준수**

**응답 형식** (JSON):
다음 오류들에 대해 각각 3개씩 대안을 생성하세요:
{errors_text}

```json
{{
  "alternatives": {{
    "{errors[0] if errors else '오류1'}": [
      "대안1-1: [구체적인 수정 방향] - [실제 수정될 텍스트 예시]",
      "대안1-2: [구체적인 수정 방향] - [실제 수정될 텍스트 예시]",
      "대안1-3: [구체적인 수정 방향] - [실제 수정될 텍스트 예시]"
    ]{',' if len(errors) > 1 else ''}
    {''.join([f'"{error}": [\n      "대안{i+1}-1: [구체적인 수정 방향] - [실제 수정될 텍스트 예시]",\n      "대안{i+1}-2: [구체적인 수정 방향] - [실제 수정될 텍스트 예시]",\n      "대안{i+1}-3: [구체적인 수정 방향] - [실제 수정될 텍스트 예시]"\n    ]{"," if i < len(errors)-1 else ""}' for i, error in enumerate(errors[1:], 1)])}
  }}
}}
```

**중요**: 
- 각 오류 메시지를 정확히 키로 사용하세요 (따옴표 포함)
- 오류 메시지와 정확히 일치해야 합니다
- 반드시 JSON 형식으로 응답하세요
- 각 대안은 150자 이내로 작성하되 구체적이어야 합니다"""

