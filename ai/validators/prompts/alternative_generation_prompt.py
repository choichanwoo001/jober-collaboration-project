"""
대안 생성 프롬프트
"""

def get_alternative_generation_prompt(stage: str, error: str, template_content: str) -> str:
    """오류별 대안 생성 프롬프트 생성 - 검증 규칙 기반"""
    
    # 검증 규칙 정의
    validation_rules = """
## 알림톡 검증 규칙 (반드시 준수)

### 1. 정보성 메시지 요건
- 반드시 정보성 메시지여야 함
- 광고성 메시지는 불가
- 앱 설치 유도 문구 포함 불가
- 무료체험, 할인쿠폰, 포인트 적립, 경품 등 혜택 제공 안내 불가
- 개인정보 등록/특정 행위(회원가입, 클릭 등) 유도 불가
- 동의하지 않은 쿠폰 발급 안내 불가

### 2. 정형화된 템플릿 요건
- 표준 알림톡 구조를 따라야 함
- 일관된 패턴의 정형화된 템플릿이어야 함
- 계절/상황별 표현보다는 일반적 표현 사용

### 3. 변수 사용 규칙
- 개인화 변수를 적절히 포함해야 함
- 변수가 실제로 사용되어야 함
- 변수 규칙에 맞는 표준 템플릿이어야 함

### 4. 기타 템플릿 작성 규칙
- 미리보기 메시지가 포함된 완전한 템플릿이어야 함
- 서비스 광고 문구 제거한 순수 안내 템플릿이어야 함
- 알림톡 작성 가이드라인을 준수해야 함
"""
    
    return f"""다음 알림톡 템플릿 검증 오류에 대해 **검증 규칙을 준수하여 통과할 수 있는** 구체적인 대안 3개를 생성해주세요.

{validation_rules}

**검증 단계**: {stage}
**오류 내용**: {error}
**템플릿 내용**: {template_content[:500]}...

**중요 요구사항**:
1. **각 대안은 반드시 위 검증 규칙을 모두 준수해야 함**
2. **대안을 적용하면 검증을 통과할 수 있어야 함**
3. 오류의 근본 원인을 해결하는 방향으로 제시
4. 사용자가 바로 적용할 수 있는 구체적인 수정 방안
5. 원본 템플릿의 의도는 유지하면서 규칙만 준수

**응답 형식**:
각 대안은 구체적인 수정 예시를 포함해야 합니다.

대안1: [구체적인 수정 방향] - [실제 수정될 텍스트 예시]
대안2: [구체적인 수정 방향] - [실제 수정될 텍스트 예시]  
대안3: [구체적인 수정 방향] - [실제 수정될 텍스트 예시]

**예시**:
- 광고성 문구 제거 → "치과 제휴 및 혜택 문구를 제거하고 순수 안내 형태로 변경"
- 변수 추가 → "개인화 변수 추가하여 맞춤형 메시지로 변경"  
- 구조 개선 → "표준 알림톡 형식으로 재구성하여 승인 기준 준수"

각 대안은 150자 이내로 작성하되, 사용자가 결과를 예측할 수 있도록 구체적이어야 합니다."""
